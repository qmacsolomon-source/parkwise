"""
Build a small, de-duplicated YOLO subset from a large Roboflow export.

Why this exists
---------------
`data/raw/ph_vehicle_identification_v7` holds ~19.4k images, but only a few
hundred are needed to fine-tune a one-class plate detector. Roboflow exports are
usually sampled from a handful of videos, so consecutive filenames are often
near-identical frames. Taking a naive random sample puts near-duplicates in both
train and valid, which inflates validation mAP and hides real errors.

This script therefore:
  1. walks every image in the source splits,
  2. keeps only images whose average-hash is more than N bits away from every
     image already kept (cheap perceptual de-duplication),
  3. splits the survivors into train/valid/test and copies images + labels,
  4. writes a data.yaml whose `path:` is resolved for the current machine.

Usage
-----
    python scripts/make_subset.py
    python scripts/make_subset.py --total 900 --hamming 6
    python scripts/make_subset.py --source data/raw/ph_vehicle_identification_v7 \
                                  --dest   data/raw/ph_plate_subset_900
"""
from __future__ import annotations

import argparse
import random
import shutil
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit("Pillow is required: pip install Pillow")

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp", ".webp"}
SPLITS = ("train", "valid", "test")


def average_hash(path: Path, size: int = 8) -> int:
    """64-bit average hash. Raises on unreadable files so the caller can skip."""
    with Image.open(path) as im:
        grey = im.convert("L").resize((size, size), Image.LANCZOS)
        pixels = list(grey.getdata())
    mean = sum(pixels) / len(pixels)
    bits = 0
    for index, value in enumerate(pixels):
        if value >= mean:
            bits |= 1 << index
    return bits


def hamming(a: int, b: int) -> int:
    return bin(a ^ b).count("1")


def collect_pairs(source: Path) -> list[tuple[Path, Path]]:
    """Return (image, label) pairs across every split of the source dataset."""
    pairs: list[tuple[Path, Path]] = []
    for split in SPLITS:
        images_dir = source / split / "images"
        labels_dir = source / split / "labels"
        if not images_dir.is_dir():
            continue
        for image in sorted(images_dir.iterdir()):
            if image.suffix.lower() not in IMAGE_EXTS:
                continue
            label = labels_dir / f"{image.stem}.txt"
            pairs.append((image, label))
    return pairs


def select_diverse(
    pairs: list[tuple[Path, Path]], total: int, hamming_threshold: int, seed: int
) -> list[tuple[Path, Path]]:
    """Random order, then greedily keep images that differ from what's kept."""
    rng = random.Random(seed)
    shuffled = list(pairs)
    rng.shuffle(shuffled)

    kept: list[tuple[Path, Path]] = []
    kept_hashes: list[int] = []
    unreadable = 0

    for image, label in shuffled:
        if len(kept) >= total:
            break
        try:
            digest = average_hash(image)
        except Exception:
            unreadable += 1
            continue

        if any(hamming(digest, seen) <= hamming_threshold for seen in kept_hashes):
            continue

        kept.append((image, label))
        kept_hashes.append(digest)

    if unreadable:
        print(f"  skipped {unreadable} unreadable image(s)")

    return kept


def split_counts(total: int) -> dict[str, int]:
    """~80/10/10, with any rounding remainder pushed into train."""
    valid = max(1, round(total * 0.10))
    test = max(1, round(total * 0.10))
    return {"train": total - valid - test, "valid": valid, "test": test}


def write_subset(
    kept: list[tuple[Path, Path]], dest: Path, seed: int, hamming_threshold: int
) -> dict[str, int]:
    rng = random.Random(seed)
    shuffled = list(kept)
    rng.shuffle(shuffled)

    counts = split_counts(len(shuffled))
    written: dict[str, int] = {}

    cursor = 0
    for split in SPLITS:
        take = shuffled[cursor : cursor + counts[split]]
        cursor += counts[split]

        images_dir = dest / split / "images"
        labels_dir = dest / split / "labels"
        images_dir.mkdir(parents=True, exist_ok=True)
        labels_dir.mkdir(parents=True, exist_ok=True)

        for image, label in take:
            shutil.copy2(image, images_dir / image.name)
            if label.is_file():
                shutil.copy2(label, labels_dir / label.name)
            else:
                # A missing label means "no objects"; YOLO expects it to exist.
                (labels_dir / f"{image.stem}.txt").write_text("", encoding="utf-8")

        written[split] = len(take)

    (dest / "data.yaml").write_text(
        f"# Generated by scripts/make_subset.py\n"
        f"# Perceptual de-duplication: average-hash Hamming distance > {hamming_threshold}\n"
        f"path: {dest.resolve().as_posix()}\n"
        f"train: train/images\n"
        f"val: valid/images\n"
        f"test: test/images\n"
        f"\n"
        f"nc: 1\n"
        f"names: ['license_plate']\n",
        encoding="utf-8",
    )

    return written


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Build a small, de-duplicated YOLO subset from a big export."
    )
    parser.add_argument(
        "--source",
        default="data/raw/ph_vehicle_identification_v7",
        help="Source dataset root containing train/valid/test",
    )
    parser.add_argument(
        "--dest",
        default="data/raw/ph_plate_subset_900",
        help="Destination dataset root (wiped and rebuilt)",
    )
    parser.add_argument("--total", type=int, default=900, help="Images to keep")
    parser.add_argument(
        "--hamming",
        type=int,
        default=6,
        help="Average-hash distance below which an image counts as a near-duplicate",
    )
    parser.add_argument("--seed", type=int, default=42, help="Sampling seed")
    parser.add_argument(
        "--yes", action="store_true", help="Skip the confirmation prompt"
    )
    args = parser.parse_args()

    source = Path(args.source)
    dest = Path(args.dest)

    if not source.is_dir():
        sys.exit(f"Source not found: {source.resolve()}")

    print(f"Scanning {source.resolve()}")
    pairs = collect_pairs(source)
    if not pairs:
        sys.exit("No images found - is the source a YOLO dataset?")
    print(f"  found {len(pairs)} image/label pairs")

    print(f"Selecting {args.total} diverse images (hamming > {args.hamming}) ...")
    kept = select_diverse(pairs, args.total, args.hamming, args.seed)
    print(f"  kept {len(kept)} after de-duplication")
    if len(kept) < args.total:
        print("  NOTE: fewer than requested - loosen --hamming to keep more")

    if dest.exists():
        if not args.yes:
            answer = input(f"{dest.resolve()} exists. Delete and rebuild? [y/N] ")
            if answer.strip().lower() not in {"y", "yes"}:
                sys.exit("Aborted.")
        shutil.rmtree(dest)

    written = write_subset(kept, dest, args.seed, args.hamming)

    print(f"\nWrote {sum(written.values())} images to {dest.resolve()}")
    for split in SPLITS:
        print(f"  {split:<6} {written[split]}")
    print("  data.yaml")


if __name__ == "__main__":
    main()
